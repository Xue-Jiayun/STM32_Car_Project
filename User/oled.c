/* ==================== I2C软件模拟 ==================== */

static void OLED_I2C_Delay(void)
{
    uint8_t i;
    for (i = 0; i < 10; i++);
}

static void OLED_SCL_Set(void)
{
    GPIO_SetBits(OLED_SCL_PORT, OLED_SCL_PIN);
}

static void OLED_SCL_Clr(void)
{
    GPIO_ResetBits(OLED_SCL_PORT, OLED_SCL_PIN);
}

static void OLED_SDA_Set(void)
{
    GPIO_SetBits(OLED_SDA_PORT, OLED_SDA_PIN);
}

static void OLED_SDA_Clr(void)
{
    GPIO_ResetBits(OLED_SDA_PORT, OLED_SDA_PIN);
}

static void OLED_I2C_Start(void)
{
    OLED_SDA_Set();
    OLED_SCL_Set();
    OLED_I2C_Delay();
    OLED_SDA_Clr();
    OLED_I2C_Delay();
    OLED_SCL_Clr();
}

static void OLED_I2C_Stop(void)
{
    OLED_SDA_Clr();
    OLED_SCL_Set();
    OLED_I2C_Delay();
    OLED_SDA_Set();
    OLED_I2C_Delay();
}

static void OLED_I2C_WaitAck(void)
{
    OLED_SCL_Set();
    OLED_I2C_Delay();
    OLED_SCL_Clr();
    OLED_I2C_Delay();
}

static void OLED_I2C_SendByte(uint8_t byte)
{
    uint8_t i;
    for (i = 0; i < 8; i++) {
        if (byte & 0x80)
            OLED_SDA_Set();
        else
            OLED_SDA_Clr();
        byte <<= 1;
        OLED_I2C_Delay();
        OLED_SCL_Set();
        OLED_I2C_Delay();
        OLED_SCL_Clr();
        OLED_I2C_Delay();
    }
}

/* ==================== OLED写命令/数据 ==================== */

static void OLED_WriteCmd(uint8_t cmd)
{
    OLED_I2C_Start();
    OLED_I2C_SendByte(OLED_ADDRESS);   /* 从机地址，写 */
    OLED_I2C_WaitAck();
    OLED_I2C_SendByte(0x00);           /* Co=0, D/C=0 命令 */
    OLED_I2C_WaitAck();
    OLED_I2C_SendByte(cmd);
    OLED_I2C_WaitAck();
    OLED_I2C_Stop();
}

static void OLED_WriteData(uint8_t dat)
{
    OLED_I2C_Start();
    OLED_I2C_SendByte(OLED_ADDRESS);
    OLED_I2C_WaitAck();
    OLED_I2C_SendByte(0x40);           /* Co=0, D/C=1 数据 */
    OLED_I2C_WaitAck();
    OLED_I2C_SendByte(dat);
    OLED_I2C_WaitAck();
    OLED_I2C_Stop();
}

/* ==================== OLED初始化 ==================== */

void OLED_Init(void)
{
    GPIO_InitTypeDef GPIO_InitStructure;

    /* 使能GPIO时钟 */
    RCC_APB2PeriphClockCmd(OLED_GPIO_CLK, ENABLE);

    /* 配置SCL/SDA为推挽输出 */
    GPIO_InitStructure.GPIO_Pin = OLED_SCL_PIN | OLED_SDA_PIN;
    GPIO_InitStructure.GPIO_Mode = GPIO_Mode_Out_PP;
    GPIO_InitStructure.GPIO_Speed = GPIO_Speed_50MHz;
    GPIO_Init(OLED_SCL_PORT, &GPIO_InitStructure);
    GPIO_Init(OLED_SDA_PORT, &GPIO_InitStructure);

    /* SSD1306初始化序列 */
    OLED_WriteCmd(0xAE); /* 关闭显示 */

    OLED_WriteCmd(0xD5); /* 设置时钟分频 */
    OLED_WriteCmd(0x80);

    OLED_WriteCmd(0xA8); /* 设置多路复用 */
    OLED_WriteCmd(0x3F);

    OLED_WriteCmd(0xD3); /* 设置显示偏移 */
    OLED_WriteCmd(0x00);

    OLED_WriteCmd(0x40); /* 设置起始行 */

    OLED_WriteCmd(0x8D); /* 电荷泵 */
    OLED_WriteCmd(0x14);

    OLED_WriteCmd(0x20); /* 设置内存寻址模式 */
    OLED_WriteCmd(0x02); /* 页寻址模式 */

    OLED_WriteCmd(0xA1); /* 段重定向 */
    OLED_WriteCmd(0xC8); /* COM扫描方向 */

    OLED_WriteCmd(0xDA); /* COM引脚配置 */
    OLED_WriteCmd(0x12);

    OLED_WriteCmd(0x81); /* 对比度 */
    OLED_WriteCmd(0xCF);

    OLED_WriteCmd(0xD9); /* 预充电周期 */
    OLED_WriteCmd(0xF1);

    OLED_WriteCmd(0xDB); /* VCOMH电压 */
    OLED_WriteCmd(0x40);

    OLED_WriteCmd(0xA4); /* 全屏显示 */
    OLED_WriteCmd(0xA6); /* 正常显示(非反色) */

    OLED_WriteCmd(0xAF); /* 开启显示 */

    OLED_Clear();
}

void OLED_Clear(void)
{
    uint8_t page, col;
    for (page = 0; page < 8; page++) {
        OLED_WriteCmd(0xB0 + page);     /* 设置页地址 */
        OLED_WriteCmd(0x00);             /* 列低地址 */
        OLED_WriteCmd(0x10);             /* 列高地址 */
        for (col = 0; col < 128; col++) {
            OLED_WriteData(0x00);
        }
    }
}

void OLED_DisplayOn(void)
{
    OLED_WriteCmd(0x8D);
    OLED_WriteCmd(0x14);
    OLED_WriteCmd(0xAF);
}

void OLED_DisplayOff(void)
{
    OLED_WriteCmd(0x8D);
    OLED_WriteCmd(0x10);
    OLED_WriteCmd(0xAE);
}

void OLED_SetCursor(uint8_t x, uint8_t y)
{
    OLED_WriteCmd(0xB0 + (y & 0x07));           /* 页地址 */
    OLED_WriteCmd((x & 0x0F));                    /* 列低地址 */
    OLED_WriteCmd(0x10 + ((x >> 4) & 0x0F));     /* 列高地址 */
}

void OLED_ShowChar(uint8_t x, uint8_t y, char ch)
{
    uint8_t i;

    if (ch < ' ' || ch > '~')
        ch = ' ';

    OLED_SetCursor(x, y);

    /* 上半部分 */
    for (i = 0; i < 8; i++)
        OLED_WriteData(OLED_F8x16[ch - ' '][i]);

    OLED_SetCursor(x, y + 1);

    /* 下半部分 */
    for (i = 0; i < 8; i++)
        OLED_WriteData(OLED_F8x16[ch - ' '][i + 8]);
}

void OLED_ShowString(uint8_t x, uint8_t y, const char *str)
{
    uint8_t i = 0;
    while (str[i] != '\0') {
        OLED_ShowChar(x + i * 8, y, str[i]);
        i++;
    }
}

void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    uint8_t i;
    for (i = 0; i < len; i++) {
        OLED_ShowChar(x + (len - 1 - i) * 8, y, '0' + (num % 10));
        num /= 10;
    }
}
